/**
 * Generates src/components/icons/index.tsx from the normalized tier-2 SVGs.
 *
 * Run once via `npm run prep`. The output is committed source — readable,
 * diffable and reviewable — not a build-time transform. That matters because
 * a build plugin that silently stops working ships miscoloured icons with a
 * green build; a committed file can only change if somebody edits it.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join } from "node:path";

const SRC = ".svg-inline";
const OUT = "src/components/icons/index.tsx";

/** SVG presentation attributes → React camelCase props. */
const ATTR_MAP = {
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-miterlimit": "strokeMiterlimit",
  "stroke-dasharray": "strokeDasharray",
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "fill-opacity": "fillOpacity",
  "stroke-opacity": "strokeOpacity",
};

const pascal = (s) =>
  s
    .replace(/^icon-/, "")
    .split("-")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");

function toJsx(markup) {
  let out = markup;
  // Strip Illustrator's layer bookkeeping — pure noise in the DOM.
  out = out.replace(/\s+data-name="[^"]*"/g, "");
  // kebab-case attributes → React props
  for (const [k, v] of Object.entries(ATTR_MAP)) {
    out = out.replace(new RegExp(`\\s${k}="`, "g"), ` ${v}="`);
  }
  // Numeric-looking props read better as expressions, but strings are valid
  // React and keep the diff against the source SVG obvious. Leave them.
  return out;
}

const icons = [];
for (const file of readdirSync(SRC).filter((f) => f.endsWith(".svg")).sort()) {
  const raw = readFileSync(join(SRC, file), "utf8");

  const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`generate-icons: ${file} has no viewBox`);

  // Root-level presentation attributes get hoisted onto the <svg> so they can
  // be overridden per call site.
  const rootAttrs = {};
  const rootTag = raw.match(/<svg[^>]*>/)[0];
  for (const m of rootTag.matchAll(/\s([a-z-]+)="([^"]*)"/g)) {
    if (["xmlns", "viewBox"].includes(m[1])) continue;
    rootAttrs[ATTR_MAP[m[1]] ?? m[1]] = m[2];
  }

  const inner = toJsx(raw.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, ""));

  const name = pascal(file.replace(/\.svg$/, "")) + "Icon";
  const attrLines = Object.entries(rootAttrs)
    .map(([k, v]) => `      ${k}="${v}"`)
    .join("\n");

  icons.push(
    `export function ${name}(props: SVGProps<SVGSVGElement>) {\n` +
      `  return (\n` +
      `    <svg\n` +
      `      viewBox="${viewBox}"\n` +
      (attrLines ? attrLines + "\n" : "") +
      `      aria-hidden="true"\n` +
      `      focusable="false"\n` +
      `      {...props}\n` +
      `    >\n` +
      `      ${inner}\n` +
      `    </svg>\n` +
      `  );\n` +
      `}`,
  );
}

mkdirSync("src/components/icons", { recursive: true });
writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-icons.mjs — do not edit by hand.\n` +
    `// Source: assets/source/svg/icon-*.svg, normalized by scripts/normalize-svgs.mjs.\n` +
    `//\n` +
    `// These carry stroke="currentColor", so colour is driven by Tailwind text\n` +
    `// utilities (needed for the footer's social-icon hover states). They render\n` +
    `// in Server Components — no client boundary.\n` +
    `import type { SVGProps } from "react";\n\n` +
    icons.join("\n\n") +
    "\n",
);

console.log(`✓ ${icons.length} icon components → ${OUT}`);
